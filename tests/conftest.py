class FakeLLMClient:
    def __init__(
        self,
        *,
        summary: str = "Summary generated by the fake LLM.",
        proposals: Optional[List[Dict[str, Any]]] = None,
        matches: Optional[List[Dict[str, Any]]] = None,
        draft_reply: Optional[Dict[str, Any]] = None,
    ) -> None:
        self.summary = summary
        self.proposals = proposals or []
        self.matches = matches or []
        self.draft_reply = draft_reply

    def summarize_email(self, **kwargs: Any) -> Dict[str, Any]:
        return {
            "text": self.summary,
            "proposals": list(self.proposals),
            "draft_reply": self.draft_reply,
        }

    def evaluate_label_rules(self, **kwargs: Any) -> Dict[str, Any]:
        return {
            "matches": list(self.matches),
        }


