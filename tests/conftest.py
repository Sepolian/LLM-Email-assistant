class FakeGCalClient:
    def __init__(self) -> None:
        self.service = object()
        self.events: List[Dict[str, Any]] = []
        self.created: List[Dict[str, Any]] = []
        self.updated: List[Dict[str, Any]] = []
        self.deleted: List[str] = []

    def list_events(self, max_results: int = 50, time_min: Optional[str] = None, time_max: Optional[str] = None) -> List[Dict[str, Any]]:
        return list(self.events)[:max_results]

    def create_event(self, proposal: Dict[str, Any]) -> str:
        self.created.append(dict(proposal))
        return f"event-{len(self.created)}"

    def update_event(self, event_id: str, updates: Dict[str, Any]) -> str:
        self.updated.append({"event_id": event_id, "updates": dict(updates)})
        return event_id

    def delete_event(self, event_id: str) -> bool:
        self.deleted.append(event_id)
        return True


def make_context(
    *,
    runtime: AgentRuntime,
    thread_id: str,
    gmail_client: Optional[FakeGmailClient] = None,
    gcal_client: Optional[FakeGCalClient] = None,
    user_id: str = "tester@example.com",
    agent_kind: str = "chat",
    mode: str = "semi_auto",
    shadow_mode: bool = False,
    source: str = "chat",
    rules: Optional[List[Dict[str, Any]]] = None,
    automation_settings: Optional[Dict[str, Any]] = None,
) -> InvocationContext:
    return InvocationContext(
        thread_id=thread_id,
        user_id=user_id,
        agent_kind=agent_kind,  # type: ignore[arg-type]
        mode=mode,  # type: ignore[arg-type]
        shadow_mode=shadow_mode,
        source=source,
        gmail_client=gmail_client,
        gcal_client=gcal_client,
        llm_client=runtime.llm_client,
        rules=rules or [],
        automation_settings=automation_settings or {},
    )


